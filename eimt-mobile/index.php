        // Registration form validation
        document.getElementById('registrationForm').addEventListener('submit', async function (e) {
            e.preventDefault();

            const name = document.getElementById('regName').value.trim();
            const email = document.getElementById('regEmail').value.trim();
            const phone = document.getElementById('regPhone').value.trim();
            const program = document.getElementById('regProgram').value;
            const amount = document.getElementById('regAmount').value.trim();

            let hasError = false;

            // Clear previous errors
            document.querySelectorAll('#registrationForm .field-error').forEach(el => {
                el.classList.remove('show');
                el.textContent = '';
            });
            document.getElementById('regResponseError').classList.remove('show');

            // Validate name
            if (!name || name.length < 3) {
                const error = document.getElementById('regNameError');
                error.textContent = 'Please enter your full name (minimum 3 characters).';
                error.classList.add('show');
                hasError = true;
            }

            // Validate email
            if (!email || !/^[^\s@]+@[^\s@]+\.[^\s@]{2,}$/.test(email)) {
                const error = document.getElementById('regEmailError');
                error.textContent = 'Please enter a valid email address.';
                error.classList.add('show');
                hasError = true;
            }

            // Validate phone
            const cleanedPhone = phone.replace(/[\s()\-]/g, '');
            if (!phone || !/^\+?[0-9]{10,15}$/.test(cleanedPhone)) {
                const error = document.getElementById('regPhoneError');
                error.textContent = 'Please enter a valid phone number (10-15 digits).';
                error.classList.add('show');
                hasError = true;
            }

            // Validate program
            if (!program) {
                const error = document.getElementById('regProgramError');
                error.textContent = 'Please select a program.';
                error.classList.add('show');
                hasError = true;
            }

            // Validate amount
            if (!amount || isNaN(amount) || parseInt(amount) < 1) {
                const error = document.getElementById('regAmountError');
                error.textContent = 'Please enter a valid amount (minimum 1 USD).';
                error.classList.add('show');
                hasError = true;
            }

            if (hasError) return;

            // Proceed with payment
            const submitBtn = document.getElementById('regSubmitBtn');
            submitBtn.disabled = true;
            submitBtn.textContent = 'Processing...';

            try {
                await processRegistrationPayment(name, email, phone, program, parseInt(amount));
            } catch (error) {
                const errorEl = document.getElementById('regResponseError');
                errorEl.textContent = error.message || 'Payment failed. Please try again.';
                errorEl.classList.add('show');
                submitBtn.disabled = false;
                submitBtn.textContent = 'Proceed to Payment';
            }
        });

        // Load Razorpay script
        function loadRazorpayScript() {
            return new Promise((resolve) => {
                if (typeof Razorpay !== "undefined") {
                    resolve(true);
                    return;
                }

                const script = document.createElement("script");
                script.src = "https://checkout.razorpay.com/v1/checkout.js";
                script.async = true;

                script.onload = () => resolve(true);
                script.onerror = () => resolve(false);

                document.body.appendChild(script);
            });
        }

        // Process registration payment
        async function processRegistrationPayment(name, email, phone, program, amount) {
            const isScriptLoaded = await loadRazorpayScript();
            if (!isScriptLoaded) {
                throw new Error("Failed to load payment gateway. Please check your internet connection.");
            }

            const response = await fetch("https://api.123admissions.com/api/v1/create-order-an", {
                method: "POST",
                headers: { "Content-Type": "application/json" },
                body: JSON.stringify({
                    amount: amount,
                    type: "registration",
                    description: `EIMT ${program} Registration Fee`,
                    name: name,
                    email: email,
                    phone: phone,
                    program: program
                })
            });

            if (!response.ok) {
                throw new Error("Failed to create payment order. Please try again.");
            }

            const order = await response.json();
            console.log("Order created:", order);

            const options = {
                key: "rzp_live_03ijsdCrvMvOp9",
                amount: order.amount,
                currency: order.currency || "USD",
                name: "EIMT",
                description: `${program} Program Registration`,
                order_id: order.id,
                image: "https://collegeall.com/emit-mobile/img/logo_Eimt.webp",
                prefill: {
                    name: name,
                    email: email,
                    contact: phone
                },
                theme: {
                    color: "#003266"
                },
                handler: function (response) {
                    console.log("Registration successful", response);
                    alert("Registration successful! Payment ID: " + response.razorpay_payment_id);
                    closeRegistrationModal();
                    window.location.href = "./registration-success/";
                },
                modal: {
                    ondismiss: function () {
                        console.log("Payment modal closed");
                        const btn = document.getElementById('regSubmitBtn');
                        btn.disabled = false;
                        btn.textContent = 'Proceed to Payment';
                    }
                }
            };

            const razorpay = new Razorpay(options);
            razorpay.open();
        }

        // Close modal on escape key
        document.addEventListener('keydown', function (e) {
            if (e.key === 'Escape') {
                closeRegistrationModal();
            }
        });
