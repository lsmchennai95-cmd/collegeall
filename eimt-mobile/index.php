            try {

                const payload = {

                    user_id: insertId,

                    otp: otp

                };

                console.log("OTP payload:", payload);

                const result = await verifyEnquiryOtp(payload);

                console.log("OTP result:", result);

                if (result.status === 200 && result.error === false) {

                    clearOtpTimer(type);

                    if (type === "modal") {

                        closeEnquiryModal(true);

                    }

                    window.location.href = "./thank-you/";

                    return;

                }

                throw new Error(result.message || "Invalid OTP. Please try again.");

            } catch (error) {

                console.error("OTP verification failed:", error);

                showInlineError(type, error.message || "Unable to verify OTP. Please try again.");

                markOtpError(type);

            } finally {

                if (verifyButton) {

                    verifyButton.disabled = false;

                    verifyButton.textContent = originalText;

                }

            }

        }

