if (!function_exists('schema_course')) {
    /**
     * Generate Course Schema
     */
    function schema_course(array $course): array {
        $schema = [
            '@context'    => 'https://schema.org',
            '@type'       => 'Course',
            'name'        => $course['name'],
            'description' => $course['description'] ?? '',
            'url'         => canonical_url($course['url'] ?? ''),
            'provider'    => [
                '@type' => 'CollegeOrUniversity',
                'name'  => $course['university'] ?? 'CollegeAll Partner University',
                'url'   => canonical_url($course['university_url'] ?? '')
            ]
        ];

        if (!empty($course['fee'])) {
            $rawFee = preg_replace('/[^\d]/', '', $course['fee']);
            if ($rawFee !== '') {
                $schema['offers'] = [
                    '@type'         => 'Offer',
                    'price'         => $rawFee,
                    'priceCurrency' => 'INR',
                    'category'      => 'Online Degree Program',
                    'availability'  => 'https://schema.org/InStock'
                ];
            }
        }

        if (!empty($course['duration'])) {
            $schema['hasCourseInstance'] = [
                '@type'          => 'CourseInstance',
                'courseMode'     => 'Online',
                'courseWorkload' => $course['duration']
            ];
        }

        return $schema;
    }
}

if (!function_exists('schema_educational_org')) {
     
    function schema_educational_org(array $univ): array {
        $schema = [
            '@context'    => 'https://schema.org',
            '@type'       => 'CollegeOrUniversity',
            'name'        => $univ['name'],
            'url'         => canonical_url($univ['url'] ?? ''),
            'description' => $univ['description'] ?? ''
        ];

        if (!empty($univ['logo'])) {
            $schema['logo'] = $univ['logo'];
            $schema['image'] = $univ['logo'];
        }

        return $schema;
    }
}

if (!function_exists('schema_article')) {
     
    function schema_article(array $article): array {
        return [
            '@context'         => 'https://schema.org',
            '@type'            => 'BlogPosting',
            'headline'         => $article['headline'],
            'description'      => $article['description'] ?? '',
            'url'              => canonical_url($article['url'] ?? ''),
            'mainEntityOfPage' => [
                '@type' => 'WebPage',
                '@id'   => canonical_url($article['url'] ?? '')
            ],
            'publisher'        => [
                '@type' => 'Organization',
                'name'  => 'CollegeAll',
                'logo'  => [
                    '@type' => 'ImageObject',
                    'url'   => 'https://api.collegeall.com/Logo/collegeallLogo.png'
                ]
            ],
            'datePublished'    => $article['datePublished'] ?? '2026-01-01',
            'image'            => $article['image'] ?? 'https://api.collegeall.com/Logo/og-image.png'
        ];
    }
