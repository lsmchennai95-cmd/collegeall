if (!function_exists('canonical_url')) {
    
    function canonical_url(string $path = ''): string {
        $base = function_exists('config') ? config('canonical_base_url', 'https://collegeall.com') : 'https://collegeall.com';
        $base = rtrim($base, '/');

        if ($path === '' || $path === '/') {
            return $base . '/';
        }

  
        if (preg_match('#^https?://#i', $path)) {
            $parsed = parse_url($path);
            $path = $parsed['path'] ?? '/';
        }

        $trimmed = trim($path, '/');
        if ($trimmed === '') {
            return $base . '/';
        }

        $hasExt = (bool) pathinfo($trimmed, PATHINFO_EXTENSION);
        $suffix = $hasExt ? '' : '/';

        return $base . '/' . $trimmed . $suffix;
    }
}

if (!function_exists('render_seo_meta')) {
    
    function render_seo_meta(array $options): string {
        $title = $options['title'] ?? 'CollegeAll | Online Degrees & Courses from Top Indian Universities';
        $description = $options['description'] ?? 'Enroll in UGC-approved online MBA, MCA, BBA, and degree programs from premier Indian universities with CollegeAll. Compare courses, fees, and career outcomes.';
        $keywords = $options['keywords'] ?? null;
        $canonicalPath = $options['canonical'] ?? ($options['path'] ?? '/');
        $canonicalUrl = canonical_url($canonicalPath);
        $robots = $options['robots'] ?? 'index, follow';

        // Open Graph
        $ogType = $options['og_type'] ?? 'website';
        $ogTitle = $options['og_title'] ?? $title;
        $ogDesc = $options['og_description'] ?? $description;
        $ogImage = $options['og_image'] ?? 'https://api.collegeall.com/Logo/og-image.png';
        $ogUrl = $options['og_url'] ?? $canonicalUrl;
        $siteName = 'CollegeAll';

        // Twitter Card
        $twitterCard = $options['twitter_card'] ?? 'summary_large_image';
        $twitterTitle = $options['twitter_title'] ?? $ogTitle;
        $twitterDesc = $options['twitter_description'] ?? $ogDesc;
        $twitterImage = $options['twitter_image'] ?? $ogImage;
        $twitterSite = $options['twitter_site'] ?? '@CollegeAll';

        $html = [];
        $html[] = '<!-- SEO Metadata generated by CollegeAll SEO Engine -->';
        $html[] = '<title>' . htmlspecialchars($title, ENT_QUOTES, 'UTF-8') . '</title>';
        $html[] = '<meta name="description" content="' . htmlspecialchars($description, ENT_QUOTES, 'UTF-8') . '">';

        if (!empty($keywords)) {
            $html[] = '<meta name="keywords" content="' . htmlspecialchars($keywords, ENT_QUOTES, 'UTF-8') . '">';
        }

        $html[] = '<meta name="robots" content="' . htmlspecialchars($robots, ENT_QUOTES, 'UTF-8') . '">';
        $html[] = '<link rel="canonical" href="' . htmlspecialchars($canonicalUrl, ENT_QUOTES, 'UTF-8') . '">';

        // Open Graph
        $html[] = '<meta property="og:type" content="' . htmlspecialchars($ogType, ENT_QUOTES, 'UTF-8') . '">';
        $html[] = '<meta property="og:site_name" content="' . htmlspecialchars($siteName, ENT_QUOTES, 'UTF-8') . '">';
        $html[] = '<meta property="og:locale" content="en_IN">';
        $html[] = '<meta property="og:title" content="' . htmlspecialchars($ogTitle, ENT_QUOTES, 'UTF-8') . '">';
        $html[] = '<meta property="og:description" content="' . htmlspecialchars($ogDesc, ENT_QUOTES, 'UTF-8') . '">';
        $html[] = '<meta property="og:url" content="' . htmlspecialchars($ogUrl, ENT_QUOTES, 'UTF-8') . '">';
        $html[] = '<meta property="og:image" content="' . htmlspecialchars($ogImage, ENT_QUOTES, 'UTF-8') . '">';

        // Twitter
        $html[] = '<meta name="twitter:card" content="' . htmlspecialchars($twitterCard, ENT_QUOTES, 'UTF-8') . '">';
        $html[] = '<meta name="twitter:site" content="' . htmlspecialchars($twitterSite, ENT_QUOTES, 'UTF-8') . '">';
        $html[] = '<meta name="twitter:title" content="' . htmlspecialchars($twitterTitle, ENT_QUOTES, 'UTF-8') . '">';
        $html[] = '<meta name="twitter:description" content="' . htmlspecialchars($twitterDesc, ENT_QUOTES, 'UTF-8') . '">';
        $html[] = '<meta name="twitter:image" content="' . htmlspecialchars($twitterImage, ENT_QUOTES, 'UTF-8') . '">';

        // JSON-LD Structured Data
        if (!empty($options['schema'])) {
            $schemaData = $options['schema'];
            $html[] = '<script type="application/ld+json">';
            $html[] = json_encode($schemaData, JSON_UNESCAPED_SLASHES | JSON_UNESCAPED_UNICODE | JSON_PRETTY_PRINT);
            $html[] = '</script>';
        }

        return implode("\n    ", $html);
    }
}

