      function updateCardPositions() {
        for (let step = 1; step <= totalSteps; step++) {
          const card = cardMap[step];
          if (!card) continue;
          card.classList.remove('active', 'peek');

          if (step === currentStep) {
            card.style.transformOrigin = 'center center';
            card.style.transform = 'translateX(0) translateY(0) rotate(0deg) scale(1)';
            card.style.zIndex = 100;
            card.style.opacity = 1;
            card.style.pointerEvents = 'auto';
            card.classList.add('active');
          } else if (step < currentStep) {
            const depth = currentStep - step;
            const offsetX = -(34 + (depth - 1) * 20);
            const rotate = -(2.5 + (depth - 1) * 1.5);
            card.style.transformOrigin = 'center center';
            card.style.transform = `translateX(${offsetX}px) translateY(0) rotate(${rotate}deg) scale(1)`;
            card.style.zIndex = 90 - depth * 3;
            card.style.opacity = 1;
            card.style.pointerEvents = 'none';
            card.classList.add('peek');
          } else {
            const depth = step - currentStep;
            const offsetX = 34 + (depth - 1) * 20;
            const rotate = 2.5 + (depth - 1) * 1.5;
            card.style.transformOrigin = 'center bottom';
            card.style.transform = `translateX(${offsetX}px) translateY(0) rotate(${rotate}deg) scale(1)`;
            card.style.zIndex = 90 - depth * 3;
            card.style.opacity = 1;
            card.style.pointerEvents = 'none';
            card.classList.add('peek');
          }
        }
