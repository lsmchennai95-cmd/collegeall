      const emailError = document.getElementById('emailError');
      const phoneError = document.getElementById('phoneError');
      const submitBtn = document.getElementById('submitLeadBtn');
      const leadFormWrapper = document.getElementById('leadFormWrapper');
      const successMessage = document.getElementById('successMessage');
      const leadFormFooter = document.getElementById('leadFormFooter');

      function validateName() {
        const val = nameInput.value.trim();
        const ok = val.length >= 2 && /^[a-zA-Z\s.'-]+$/.test(val);
        nameInput.classList.toggle('error', !ok);
        nameError.classList.toggle('show', !ok);
        return ok;
      }

      function validateEmail() {
        const val = emailInput.value.trim();
        const ok = /^[^\s@]+@[^\s@]+\.[^\s@]+$/.test(val);
        emailInput.classList.toggle('error', !ok);
        emailError.classList.toggle('show', !ok);
        return ok;
      }

      function validatePhone() {
        const val = phoneInput.value.replace(/\D/g, '');
        const ok = val.length >= 10 && val.length <= 12;
        phoneInput.classList.toggle('error', !ok);
        phoneError.classList.toggle('show', !ok);
        return ok;
      }

      if (nameInput) {
        nameInput.addEventListener('blur', validateName);
        nameInput.addEventListener('input', () => { if (nameInput.classList.contains('error')) validateName(); });
      }
      if (emailInput) {
        emailInput.addEventListener('blur', validateEmail);
        emailInput.addEventListener('input', () => { if (emailInput.classList.contains('error')) validateEmail(); });
      }
      if (phoneInput) {
        phoneInput.addEventListener('blur', validatePhone);
        phoneInput.addEventListener('input', () => {
          phoneInput.value = phoneInput.value.replace(/[^\d\s+()-]/g, '');
          if (phoneInput.classList.contains('error')) validatePhone();
        });
      }

      // ===== BITRIX24 HELPERS =====
      function getQueryParam(name) {
        return new URLSearchParams(window.location.search).get(name) || '';
      }

      function buildTimelineComment(answers, pageUrl, referrer) {
        const timestamp = new Date().toLocaleString('en-IN', {
          timeZone: 'Asia/Kolkata',
          day: '2-digit', month: '2-digit', year: 'numeric',
          hour: '2-digit', minute: '2-digit', second: '2-digit', hour12: true
        });

        let comment = '📋 New LIBA Online Inquiry\n\n';
        comment += '─── Source ───\n';
        comment += 'Page URL: ' + pageUrl + '\n';
        comment += 'Referrer: ' + (referrer || 'Direct') + '\n';
        comment += 'Submitted: ' + timestamp + '\n';

        const utmKeys = ['utm_source', 'utm_medium', 'utm_campaign', 'utm_term', 'utm_content', 'gclid', 'fbclid'];
        const utmLines = [];
        utmKeys.forEach(function(key) {
          var val = getQueryParam(key);
          if (val) utmLines.push(key + ': ' + val);
        });
        if (utmLines.length > 0) {
          comment += '\n─── UTM / Click IDs ───\n' + utmLines.join('\n') + '\n';
        }

        comment += '\n─── Flow Answers ───\n';
        comment += 'Programme: LIBA Online (PhD / DBA)\n';
        comment += 'Current Role: ' + (answers.step1 || 'N/A') + '\n';
        comment += 'Motivation: ' + (answers.step2 || 'N/A') + '\n';
        comment += 'Work Experience: ' + (answers.step3 || 'N/A') + '\n';
        comment += 'Industry: ' + (answers.step4 || 'N/A') + '\n';
        comment += 'Biggest Worry: ' + (answers.step5 || 'N/A') + '\n';
        comment += 'Weekly Study Hours: ' + (answers.step6 || 'N/A') + '\n';
        comment += 'Refund Assistance: ' + (answers.step7 || 'N/A') + '\n';

        comment += '\n─── Device / Session ───\n';
        comment += 'User Agent: ' + navigator.userAgent + '\n';

        return comment;
