      function updateUI() {
        for (let step = 1; step <= totalSteps; step++) {
          const card = cardMap[step];
          if (!card) continue;
          const prevBtn = card.querySelector('[data-nav="prev"]');
          if (prevBtn) prevBtn.disabled = (step === 1);
        }
      }

      let isAnimating = false;

      function goToStep(newStep, direction) {
        if (isAnimating) return;
        if (newStep < 1 || newStep > totalSteps) return;
        if (newStep === currentStep) return;

        isAnimating = true;
        const oldCard = cardMap[currentStep];
        const newCard = cardMap[newStep];

        const slideOutX = direction === 'next' ? -240 : 240;
        const slideOutRotate = direction === 'next' ? -18 : 18;

        oldCard.style.transformOrigin = 'center center';
        oldCard.style.transition = 'transform 0.6s cubic-bezier(0.4, 0, 0.2, 1), opacity 0.4s';
        oldCard.style.transform = `translateX(${slideOutX}px) translateY(0) rotate(${slideOutRotate}deg) scale(0.95)`;
        oldCard.style.opacity = '0';
        oldCard.style.zIndex = 80;

        const startX = direction === 'next' ? 160 : -160;
        const startRotate = direction === 'next' ? 16 : -16;

        newCard.style.transformOrigin = 'center center';
        newCard.style.transition = 'none';
        newCard.style.transform = `translateX(${startX}px) translateY(0) rotate(${startRotate}deg) scale(0.96)`;
        newCard.style.opacity = '0.6';
        newCard.style.zIndex = 95;

        void newCard.offsetWidth;

        newCard.style.transition = 'transform 0.6s cubic-bezier(0.4, 0, 0.2, 1), opacity 0.4s';

