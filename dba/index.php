      async function bitrixPost(method, body) {
        const res = await fetch(BITRIX_LEAD_WEBHOOK + '/' + method, {
          method: 'POST',
          headers: { 'Content-Type': 'application/json' },
          body: JSON.stringify(body)
        });
        if (!res.ok) {
          throw new Error('Bitrix HTTP error ' + res.status + ' on ' + method);
        }
        const data = await res.json();
        if (data.error) {
          throw new Error('Bitrix API error on ' + method + ': ' + (data.error_description || data.error));
        }
        return data;
      }

      async function submitToBitrix(leadData, timelineComment) {
        // Step 1: Create lead
        const leadPayload = {
          fields: {
            TITLE: 'LIBA Online Inquiry – ' + leadData.name,
            NAME: leadData.name,
            PHONE: [{ VALUE: leadData.phone, VALUE_TYPE: 'WORK' }],
            EMAIL: [{ VALUE: leadData.email, VALUE_TYPE: 'WORK' }],
            SOURCE_ID: BITRIX_SOURCE_ID,
            SOURCE_DESCRIPTION: leadData.pageUrl,
            [BITRIX_CAMPAIGN_FIELD]: BITRIX_CAMPAIGN,
            [BITRIX_EXTRA_FIELD]: BITRIX_EXTRA_VALUE,
            COMMENTS: timelineComment,
            STATUS_ID: 'NEW'
          },
          params: { REGISTER_SONET_EVENT: 'Y' }
        };

        const leadResponse = await bitrixPost('crm.lead.add.json', leadPayload);

        if (!leadResponse.result) {
          throw new Error('Bitrix lead.add returned no result ID');
        }

        const leadId = leadResponse.result;

        // Step 2: Add timeline comment
        const commentPayload = {
          fields: {
            ENTITY_ID: leadId,
            ENTITY_TYPE: 'lead',
            COMMENT: timelineComment
          }
        };

        await bitrixPost('crm.timeline.comment.add.json', commentPayload);

        return leadId;
      }

