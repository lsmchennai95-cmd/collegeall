        function setupOtpInputs() {

            const groups = [
                "hero-otp",
                "scholar-otp",
                "modal-otp"
            ];


            groups.forEach(
                function (className) {

                    const inputs = [
                        ...document.querySelectorAll(
                            "." + className
                        )
                    ];


                    inputs.forEach(
                        function (input, index) {

                            /*
                            * Numeric keyboard
                            */

                            input.setAttribute(
                                "inputmode",
                                "numeric"
                            );

                            input.setAttribute(
                                "maxlength",
                                "1"
                            );


                            /*
                            * Input
                            */

                            input.addEventListener(
                                "input",
                                function () {

                                    this.value =
                                        this.value.replace(
                                            /\D/g,
                                            ""
                                        );


                                    this.classList.remove(
                                        "error"
                                    );


                                    if (
                                        this.value &&
                                        index <
                                            inputs.length - 1
                                    ) {

                                        inputs[
                                            index + 1
                                        ].focus();

                                    }

                                }
                            );


                            /*
                            * Backspace
                            */

                            input.addEventListener(
                                "keydown",
                                function (event) {

                                    if (
                                        event.key ===
                                            "Backspace" &&
                                        !this.value &&
                                        index > 0
                                    ) {

                                        inputs[
                                            index - 1
                                        ].focus();

                                    }

                                }
                            );


                            /*
                            * Paste 4 digit OTP
                            */

                            input.addEventListener(
                                "paste",
                                function (event) {

                                    event.preventDefault();


                                    const clipboard =
                                        event.clipboardData ||
                                        window.clipboardData;


                                    if (!clipboard) {
                                        return;
                                    }


                                    const pasted =
                                        clipboard
                                            .getData("text")
                                            .replace(
                                                /\D/g,
                                                ""
                                            )
                                            .slice(
                                                0,
                                                4
                                            );


                                    pasted
                                        .split("")
                                        .forEach(
                                            function (
                                                digit,
                                                digitIndex
                                            ) {

                                                if (
                                                    inputs[
                                                        digitIndex
                                                    ]
                                                ) {

                                                    inputs[
                                                        digitIndex
                                                    ].value =
                                                        digit;

                                                }

                                            }
                                        );


                                    if (
                                        pasted.length
                                    ) {

                                        const focusIndex =
                                            Math.min(
                                                pasted.length,
                                                inputs.length
                                            ) - 1;


                                        if (
                                            inputs[
                                                focusIndex
                                            ]
                                        ) {

                                            inputs[
                                                focusIndex
                                            ].focus();

                                        }

                                    }

                                }
                            );

                        }
                    );

                }
            );

        }


