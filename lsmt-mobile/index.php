        function toggleFaq(button) {

            const currentItem =
                button.closest(
                    ".faq-item, .faq"
                );


            if (!currentItem) {
                return;
            }


            const currentAnswer =
                currentItem.querySelector(
                    ".faq-answer"
                );


            const currentIcon =
                currentItem.querySelector(
                    ".faq-icon"
                );


            if (!currentAnswer) {
                return;
            }


            const wasOpen =
                currentAnswer.classList.contains(
                    "open"
                ) ||
                !currentAnswer.classList.contains(
                    "hidden"
                );


            document
                .querySelectorAll(
                    ".faq-answer"
                )
                .forEach(
                    function (answer) {

                        answer.classList.add(
                            "hidden"
                        );

                        answer.classList.remove(
                            "open"
                        );

                    }
                );


            document
                .querySelectorAll(
                    ".faq-icon"
                )
                .forEach(
                    function (icon) {

                        icon.textContent =
                            "+";

                    }
                );


            if (!wasOpen) {

                currentAnswer.classList.remove(
                    "hidden"
                );

                currentAnswer.classList.add(
                    "open"
                );


                if (currentIcon) {

                    currentIcon.textContent =
                        "−";

                }

            }

        }


