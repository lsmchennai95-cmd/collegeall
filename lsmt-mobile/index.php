            /*
            * Get submission ID
            */

            const insertId =
                formState[type].insertId;


            if (!insertId) {

                if (errorElement) {

                    errorElement.textContent =
                        "Submission ID is missing. Please submit the form again.";

                    errorElement.classList.add(
                        "show"
                    );

                }

                return;

            }


            /*
            * Get verify button
            */

            const verifyButton =
                getVerifyButton(type);


            const originalText =
                verifyButton
                    ? verifyButton.textContent
                    : "Verify OTP";


            if (verifyButton) {

                verifyButton.disabled =
                    true;

                verifyButton.textContent =
                    "Verifying...";

            }


            try {

                /*
                * IMPORTANT:
                *
                * The working API expects:
                *
                * {
                *     user_id: insertId,
                *     otp: otp
                * }
                */

                const payload = {

                    user_id:
                        insertId,

                    otp:
                        otp

                };


                console.log(
                    "OTP verification payload:",
                    payload
                );


                const result =
                    await verifyEnquiryOtp(
                        payload
                    );


                console.log(
                    "OTP verification response:",
                    result
                );


                /*
                * Successful response
                */

                if (
                    result.status === 200 &&
                    result.error === false
                ) {

                    clearOtpTimer(type);


                    /*
                    * Close modal ONLY after
                    * successful OTP verification.
                    */

                    if (
                        type === "modal"
                    ) {

                        closeEnquiryModal();

                    }


                    /*
                    * Redirect to thank-you page
                    */

                    window.location.href =
                        "./thank-you/";


                    return;

                }


                /*
                * Invalid OTP
                */

                throw new Error(
                    result.message ||
                    "Invalid OTP. Please try again."
                );


            } catch (error) {

                console.error(
                    "OTP verification failed:",
                    error
                );


                if (errorElement) {

                    errorElement.textContent =
                        error.message ||
                        "Unable to verify OTP. Please try again.";

                    errorElement.classList.add(
                        "show"
                    );

                }


                /*
                * Highlight OTP inputs
                */

                document
                    .querySelectorAll(
                        "." + otpClass(type)
                    )
                    .forEach(function (input) {

                        input.classList.add(
                            "error"
                        );

                    });


            } finally {

                if (verifyButton) {

                    verifyButton.disabled =
                        false;

                    verifyButton.textContent =
                        originalText;

                }

            }

        }


