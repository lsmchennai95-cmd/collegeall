        function validateLeadFields(data) {

            const errors = {};

            const name =
                String(data.name || "").trim();

            const email =
                String(data.email || "").trim();

            const phone =
                String(data.phone || "").trim();

            const program =
                String(data.program || "").trim();


            /* NAME */

            if (!name) {

                errors.name =
                    "Full name is required.";

            } else if (name.length < 3) {

                errors.name =
                    "Minimum 3 characters required.";

            } else if (
                !/^[A-Za-zÀ-ÿ.'\s]+$/.test(name)
            ) {

                errors.name =
                    "Please enter a valid name.";

            }


            /* EMAIL */

            if (!email) {

                errors.email =
                    "Email is required.";

            } else if (
                !/^[^\s@]+@[^\s@]+\.[^\s@]{2,}$/.test(email)
            ) {

                errors.email =
                    "Please enter a valid email address.";

            }


            /* PHONE */

            const cleanedPhone =
                phone.replace(/[\s()\-]/g, "");


            if (!phone) {

                errors.phone =
                    "Phone number is required.";

            } else if (
                !/^\+?[0-9]{10,15}$/.test(cleanedPhone)
            ) {

                errors.phone =
                    "Please enter a valid phone number.";

            }


            /* PROGRAM */

            if (
                program !== "MBA" &&
                program !== "DBA"
            ) {

                errors.program =
                    "Please select MBA or DBA.";

            }


            return errors;
        }


