        async function submitLead(type) {

            const data = getFormData(type);

            const errors = validateLeadFields(data);

            const prefix = getPrefix(type);

            renderErrors(prefix, errors);

            if (Object.keys(errors).length > 0) {

                const firstError = document.querySelector(
                    "#" + prefix + "Form .error"
                );

                if (firstError) {
                    firstError.focus();
                }

                return;
            }

            const button = getSubmitButton(type);

            const originalText = button.textContent;

            button.disabled = true;
            button.textContent = "Submitting...";

            /*
            * Clear previous API error
            */
            const responseError = document.getElementById(
                type === "hero"
                    ? "heroResponseError"
                    : type === "scholarship"
                        ? "scholarResponseError"
                        : "modalResponseError"
            );

            if (responseError) {
                responseError.textContent = "";
                responseError.classList.remove("show");
            }

            try {

                const response = await fetch(
                    API.submitLead,
                    {
                        method: "POST",

                        headers: {
                            "Content-Type": "application/json"
                        },

                        body: JSON.stringify({

                            ...data,
                            user_name: data.name,
                            source: type,
                            phone_code: "+91",
                            dob: "00.00.0000",
                            state: "Tamil Nadu",
                            city: "Chennai",
                            url: window.location.href,
                            ip_address: await getUserIpAddress()

                        })
                    }
                );

                

                const result = await response.json();

                console.log("API response:", result);


                /*
                * =========================================
                * API ERROR
                * =========================================
                */
                if (!response.ok || result.error === true) {

                    let errorMessage =
                        "Unable to submit enquiry. Please try again.";

                    if (typeof result.message === "string") {

                        errorMessage =
                            result.message.trim();

                    } else if (
                        result.message &&
                        typeof result.message === "object"
                    ) {

                        const messages =
                            Object.values(result.message)
                                .filter(Boolean)
                                .map(message =>
                                    String(message).trim()
                                );

                        errorMessage =
                            messages.join(" • ") ||
                            errorMessage;

                    }


                    throw new Error(errorMessage);
                }

                const insertId =
                    result.data?.insertId || null;


                if (!insertId) {

                    throw new Error(
                        "Submission ID was not returned by the server."
                    );

                }


                /*
                * =========================================
                * SAVE FORM STATE
                * =========================================
                */

                formState[type].insertId =
                    insertId;

                formState[type].phone =
                    data.phone;


                console.log(
                    "Saved insertId:",
                    formState[type].insertId
                );


                /*
                * =========================================
                * SHOW OTP
                * =========================================
                */

                showOtp(type);


            } catch (error) {

                console.error(
                    "Lead submission failed:",
                    error
                );


                /*
                * Show API error in correct form
                */
                if (responseError) {

                    responseError.textContent =
                        error.message ||
                        "Unable to submit enquiry. Please try again.";

                    responseError.classList.add("show");

                    /*
                    * Scroll error into view if necessary
                    */
                    responseError.scrollIntoView({
                        behavior: "smooth",
                        block: "nearest"
                    });

                } else {

                    console.error(
                        "Response error element not found for:",
                        type
                    );

                }

            } finally {

                button.disabled = false;
                button.textContent = originalText;

            }
        }


